def render_poem(poem, same_poet_items=None):
    """将一首诗数据渲染为 HTML 字符串。
    支持可选字段：tijie / famous / sources 可省略。
    same_poet_items 为同卷诗作列表 [(id, title, genre), ...]，若为 None 则不显示同卷栏。
    """
