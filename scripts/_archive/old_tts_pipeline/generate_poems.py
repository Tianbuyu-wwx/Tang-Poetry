    seal_char, poet_name_disp, poet_en, poet_summary, poet_sub = POET_INFO.get(
        pid, ("?", poem["author"], "", "", ""))

    # 诗原文
    verse_html = "\n".join('        <p>{}</p>'.format(line) for line in poem["verse"])

    # 注释
    notes_html = "\n".join(
        '        <li><span class="term">{}</span>{}</li>'.format(t, g)
        for t, g in poem["notes"]
    )

    # 赏析正文
    appr = poem.get("appreciation", {})
    appreciation_body_html = "\n".join('        <p>{}</p>'.format(p) for p in appr.get("body", []))

