def make_same_poet_section(current_id, poet_id, poet_name, items):
    "“”生成同卷诗作侧栏 HTML“”"
    html = '<div class="same-poet">\n'
    html += '  <div class="label">' + poet_name + '卷 · 同卷诗作</div>\n  <ul>\n'
    for pid, ptitle, pgenre in items:
        cls = ' class="current"' if pid == current_id else ''
        html += '    <li><a href="{}.html"{}><span>{}</span><span class="genre">{}</span></a></li>\n'.format(
            pid, cls, ptitle, pgenre)
    html += '  </ul>\n</div>'
    return html

